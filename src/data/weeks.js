export function nightFor(week, flags) {
  if (flags && flags.path === "helper" && HELPER_NIGHTS[week]) {
    return HELPER_NIGHTS[week];
  }
  return NIGHTS[week] || NIGHTS[1];
}

export function fillNight(text, player, dreams) {
  if (!text) return text;
  const d = dreams[player.dream] || dreams.footballer;
  return text.split("{name}").join(player.name).split("{goal}").join(d.goal);
}
